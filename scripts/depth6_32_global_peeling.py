#!/usr/bin/env python3
"""Fail-closed global q-peeling and residual SVD for frozen depth-6 [3,2].

Input is the complete, independently validated KEYMETA union plus every raw
master block generated by the pinned Stage-A engine. This script never rebuilds
the shell, S5 orbits, multiplicities, or assignment identity.

A PASS is issued only when every block is eliminated by a full-column-rank
unique-q witness, or the remaining global residual matrix is independently
shown full column rank. Otherwise the output remains explicitly incomplete.
"""
from __future__ import annotations
import argparse, gzip, hashlib, json, pickle
from pathlib import Path
import numpy as np

def sha256(path: Path) -> str:
    h=hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda:f.read(1024*1024),b''): h.update(chunk)
    return h.hexdigest()

def load_blocks(root: Path):
    keymeta={}
    for p in sorted(root.rglob('orbit-*.keymeta.pkl.gz')):
        with gzip.open(p,'rb') as f: b=pickle.load(f)
        oid=int(b['orbit_id'])
        if oid in keymeta: raise RuntimeError(f'duplicate KEYMETA orbit {oid}')
        keymeta[oid]=b
    raw_paths={}
    for p in sorted(root.rglob('orbit-*.raw.pkl.gz')):
        oid=int(p.name.split('-')[1].split('.')[0])
        if oid in raw_paths: raise RuntimeError(f'duplicate raw orbit {oid}')
        raw_paths[oid]=p
    if len(keymeta)!=2755 or len(raw_paths)!=2755:
        raise RuntimeError(f'incomplete inputs: keymeta={len(keymeta)}/2755 raw={len(raw_paths)}/2755')
    if set(keymeta)!=set(raw_paths): raise RuntimeError('raw and KEYMETA orbit sets differ')
    columns=sum(int(b['m']) for b in keymeta.values())
    if columns!=130903: raise RuntimeError(f'column total mismatch {columns}')
    return keymeta,raw_paths

def load_raw(oid, path, km):
    if not path.is_file(): raise RuntimeError(f'orbit {oid}: missing raw block')
    with gzip.open(path,'rb') as f: raw=pickle.load(f)
    if raw.get('kind')!='BQG_DEPTH6_32_FROZEN_MASTER_BLOCK_RAW': raise RuntimeError(f'orbit {oid}: wrong raw kind')
    if int(raw['orbit_id'])!=oid or int(raw['m'])!=int(km['m']): raise RuntimeError(f'orbit {oid}: identity mismatch')
    if raw.get('frozen_assignment_sha256')!=km.get('frozen_assignment_sha256'):
        raise RuntimeError(f'orbit {oid}: frozen identity hash mismatch')
    mm=raw.get('master_map')
    if not isinstance(mm,dict) or set(mm)!=set(km['q_rows']): raise RuntimeError(f'orbit {oid}: q-key mismatch')
    for q,M0 in mm.items():
        M=np.asarray(M0)
        if M.ndim!=2 or M.shape[1]!=int(km['m']) or M.shape[0]!=int(km['q_rows'][q]):
            raise RuntimeError(f'orbit {oid}: matrix shape mismatch at q={q!r}')
        if not np.isfinite(M).all(): raise RuntimeError(f'orbit {oid}: non-finite matrix at q={q!r}')
    return mm

def rank_witness(A, rtol):
    A=np.asarray(A)
    if A.ndim!=2 or A.shape[1]==0: raise RuntimeError('rank witness requires nonempty columns')
    U,s,Vh=np.linalg.svd(A,full_matrices=False)
    smax=float(s[0]) if len(s) else 0.0
    threshold=max(A.shape)*np.finfo(float).eps*max(smax,1.0)*100.0
    threshold=max(threshold,float(rtol)*smax)
    rank=int(np.count_nonzero(s>threshold))
    # SVD reconstruction residual is a backward-error diagnostic.
    rec=(U*s)@Vh
    backward=float(np.linalg.norm(A-rec)/max(np.linalg.norm(A),1e-300))
    return {'rank':rank,'columns':int(A.shape[1]),'rows':int(A.shape[0]),
            'sigma_max':smax,'sigma_min_estimate':float(s[-1]) if len(s) else 0.0,
            'rank_threshold':float(threshold),'relative_svd_backward_error':backward,
            'singular_values':[float(x) for x in s]}

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--root',type=Path,required=True)
    ap.add_argument('--out',type=Path,required=True)
    ap.add_argument('--rtol',type=float,default=1e-10)
    ap.add_argument('--max-residual-columns',type=int,default=2500)
    ap.add_argument('--max-residual-bytes',type=int,default=2_000_000_000)
    a=ap.parse_args()
    km,raw_paths=load_blocks(a.root)
    q_occ={}
    q_rows={}
    for oid,b in km.items():
        for q,n0 in b['q_rows'].items():
            n=int(n0)
            if q in q_rows and q_rows[q]!=n: raise RuntimeError(f'incompatible row dimensions for shared q={q!r}: {q_rows[q]} vs {n}')
            q_rows[q]=n
            q_occ[q]=q_occ.get(q,0)+1
    active=set(km)
    peeled=[]
    rounds=0
    while True:
        rounds+=1
        removed=[]
        for oid in sorted(active):
            unique=[q for q in km[oid]['q_rows'] if q_occ[q]==1]
            if not unique: continue
            mm=load_raw(oid,raw_paths[oid],km[oid])
            mats=[np.asarray(mm[q]) for q in unique]
            A=np.vstack(mats) if len(mats)>1 else mats[0]
            w=rank_witness(A,a.rtol)
            if w['rank']==int(km[oid]['m']):
                removed.append((oid,unique,w))
        if not removed: break
        for oid,unique,w in removed:
            if oid not in active: continue
            active.remove(oid)
            for q in km[oid]['q_rows']:
                q_occ[q]-=1
            peeled.append({'orbit_id':oid,'unique_q_count':len(unique),**w})
        if not active: break
        if rounds>2756: raise RuntimeError('peeling iteration bound exceeded')

    residual_columns=sum(int(km[o]['m']) for o in active)
    result={'schema_version':1,'kind':'BQG_DEPTH6_32_NUMERICAL_RANK_CERTIFICATE',
      'irrep':'[3,2]','input_blocks':2755,'input_columns':130903,
      'peeled_blocks':len(peeled),'peeled_columns':sum(x['columns'] for x in peeled),
      'peeling_rounds':rounds,'remaining_blocks':len(active),
      'remaining_columns':residual_columns,'rank_certified':False,
      'numerical_closure_claimed':False,'status':'INCOMPLETE',
      'peeling_witnesses':peeled,
      'claim_boundary':'Numerical result only for the frozen finite [3,2] master map; no continuum or physicalization claim.'}
    if not active:
        result.update({'status':'PASS_FULL_COLUMN_RANK_BY_Q_PEELING',
          'rank_certified':True,'certified_rank':130903,
          'sigma_min_lower_bound':min(x['sigma_min_estimate'] for x in peeled),
          'numerical_closure_claimed':True})
    else:
        # A shared q key plus equal row counts is not, by itself, a proof that
        # row coordinates are identically ordered across different orbit
        # blocks. Do not assemble a global residual matrix until the frozen
        # backend exposes/pins a row-basis identity contract.
        result['status']='RESIDUAL_REQUIRES_ROW_BASIS_IDENTITY_CERTIFICATE'
        result['residual_limit']={'max_columns':a.max_residual_columns,
          'max_bytes':a.max_residual_bytes,
          'reason':'cross-block q-row coordinate alignment is not yet independently certified'}
    a.out.write_text(json.dumps(result,indent=2,sort_keys=True)+'\n')
    print(json.dumps({k:v for k,v in result.items() if k not in ('peeling_witnesses','residual_svd')},sort_keys=True))
    if not result['rank_certified']: raise SystemExit(2)

if __name__=='__main__': main()
